import mongoose from "mongoose";

const userFeedSchema = new mongoose.Schema({
  description: {
    type: String,
    required: true,
  },
  image: {
    public_id: {
      type: String,
      required: true,
    },
    url: {
      type: String,
      required: true,
    },
  },
  createdAt: {
    type: Date,
    default: Date.now,
  },
  user: {
    type: mongoose.Schema.ObjectId,
    ref: "User",
    required: true,
  },
});

const Feeds = mongoose.model("Feed", userFeedSchema);

export default Feeds;
